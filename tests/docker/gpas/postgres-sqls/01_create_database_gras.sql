CREATE OR REPLACE PROCEDURE createGroupRoleMapping(projectName varchar, groupName varchar, roleName varchar)
LANGUAGE plpgsql AS $$
BEGIN
    INSERT INTO group_role_mapping(group_id,role_id)
    SELECT g.id,r.id
    FROM group_ g
             JOIN role r ON r.name=roleName
    WHERE g.name=groupName AND g.project_name=projectName;
END $$;
ALTER PROCEDURE createGroupRoleMapping(projectName varchar, groupName varchar, roleName varchar) OWNER TO gras_user;

CREATE OR REPLACE PROCEDURE grantAdminRights(domainName varchar, projectName varchar, userName varchar)
LANGUAGE plpgsql AS $$
BEGIN
    INSERT INTO permission(group_id,user_name,domain_name)
    SELECT id,userName,domainName
    FROM group_
    WHERE project_name=projectName
    ON CONFLICT DO NOTHING;
END $$;
ALTER PROCEDURE grantAdminRights(domainName varchar, projectName varchar, userName varchar) OWNER TO gras_user;

CREATE OR REPLACE PROCEDURE grantStandardRights(domainName varchar, projectName varchar, userName varchar)
LANGUAGE plpgsql AS $$
BEGIN
    DELETE FROM permission p
        USING group_ g
    WHERE p.group_id=g.id
      AND p.user_name=userName
      AND p.domain_name=domainName
      AND g.project_name=projectName;

    INSERT INTO permission(group_id,user_name,domain_name)
    SELECT id,userName,domainName
    FROM group_
    WHERE project_name=projectName
      AND name !~* 'admin'
    ON CONFLICT DO NOTHING;
END $$;
ALTER PROCEDURE grantStandardRights(domainName varchar, projectName varchar, userName varchar) OWNER TO gras_user;
