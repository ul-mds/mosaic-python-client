CREATE OR REPLACE PROCEDURE createUser(userName varchar, passwd varchar, description varchar)
LANGUAGE plpgsql AS $$
BEGIN
    INSERT INTO "user"(name,password,active,description)
    VALUES(userName, encode(digest(passwd,'sha256'),'hex'), true, description)
    ON CONFLICT(name) DO NOTHING;
END $$;
ALTER PROCEDURE createUser(userName varchar, passwd varchar, description varchar) OWNER TO gras_user;

