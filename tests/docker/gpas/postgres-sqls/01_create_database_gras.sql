DROP SCHEMA IF EXISTS gras CASCADE;
CREATE DATABASE gras;

CREATE USER gras_user WITH PASSWORD 'gras_password';
GRANT ALL PRIVILEGES ON DATABASE gras TO gras_user;

\c gras;
CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TABLE domain (
    name varchar(255) PRIMARY KEY,
    description varchar(255) NOT NULL DEFAULT ''
);
ALTER TABLE domain OWNER TO gras_user;

CREATE TABLE project (
    name varchar(255) PRIMARY KEY,
    description varchar(255) NOT NULL DEFAULT ''
);
ALTER TABLE project OWNER TO gras_user;

CREATE TABLE "user" (
    name varchar(255) PRIMARY KEY,
    password varchar(255),
    active boolean DEFAULT true,
    description varchar(255) NOT NULL DEFAULT '',
    email varchar(255) NOT NULL DEFAULT ''
);
ALTER TABLE "user" OWNER TO gras_user;

CREATE TABLE role (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(255) UNIQUE NOT NULL,
    project_name varchar(255) NOT NULL REFERENCES project(name),
    description varchar(255) NOT NULL DEFAULT ''
);
ALTER TABLE role OWNER TO gras_user;

CREATE TABLE group_ (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(255) NOT NULL,
    project_name varchar(255) NOT NULL REFERENCES project(name),
    description varchar(255) NOT NULL DEFAULT '',
    CONSTRAINT unique_name_project UNIQUE(name, project_name)
);
ALTER TABLE group_ OWNER TO gras_user;

CREATE TABLE group_role_mapping (
    group_id integer NOT NULL REFERENCES group_(id) ON DELETE CASCADE,
    role_id integer NOT NULL REFERENCES role(id),
    PRIMARY KEY(group_id, role_id)
);
ALTER TABLE group_role_mapping OWNER TO gras_user;

