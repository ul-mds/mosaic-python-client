CREATE OR REPLACE VIEW domainuser_password AS
SELECT DISTINCT concat_ws('@',p.user_name,p.domain_name) AS domainuser,  u.password
FROM permission p
JOIN "user" u ON u.name=p.user_name
WHERE u.active=true;
ALTER VIEW domainuser_password OWNER TO gras_user;

CREATE OR REPLACE VIEW domainuser_role AS
SELECT DISTINCT concat_ws('@',p.user_name,p.domain_name) AS domainuser, r.name AS role
FROM permission p
JOIN group_role_mapping m ON p.group_id=m.group_id
JOIN role r ON m.role_id=r.id
JOIN "user" u ON u.name=p.user_name
WHERE u.active=true;
ALTER VIEW domainuser_role OWNER TO gras_user;

CREATE OR REPLACE VIEW validate AS
SELECT DISTINCT a.domainuser,a.password,b.role
FROM domainuser_password a
JOIN domainuser_role b USING(domainuser);
ALTER VIEW validate OWNER TO gras_user;

CREATE OR REPLACE PROCEDURE createDomain(domainName varchar, description varchar)
LANGUAGE plpgsql AS $$
BEGIN
    INSERT INTO domain(name,description)
    VALUES(domainName,description)
    ON CONFLICT(name) DO NOTHING;
END $$;
ALTER PROCEDURE createDomain(domainName varchar, description varchar) OWNER TO gras_user;

